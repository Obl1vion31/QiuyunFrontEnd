import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {startFixture,employee} from './auth.fixture';
import * as s from '../src/db/schema';

const folder=process.env.MEETING_CREATE_EVIDENCE_DIR||'.tools/test-artifacts/meeting-create';
await mkdir(folder,{recursive:true});
const clockFile=new URL('../.tools/test-artifacts/meeting-create-clock.txt',import.meta.url).pathname;
await writeFile(clockFile,'2026-10-24T00:30:00+08:00');
const fixture=await startFixture({clockFile});let browser:any;
try{
  const playwright=await import(new URL('../.tools/tooling/node_modules/playwright/index.mjs',import.meta.url).href);
  browser=await playwright.chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},locale:'zh-CN'});
  const login=await context.request.post(fixture.baseURL+'/api/auth/sign-in/username',{headers:{Origin:fixture.baseURL},data:employee});assert.equal(login.status(),200);
  const page=await context.newPage();const errors:string[]=[],requests:string[]=[],checks:string[]=[];
  page.setDefaultTimeout(15000);
  page.on('pageerror',(e:Error)=>errors.push(e.message));
  page.on('request',(r:any)=>{if(r.url().includes('/api/meeting-reviews'))requests.push(r.method()+' '+r.url());});
  await page.goto(fixture.baseURL+'/business/meeting-review');
  await page.getByRole('button',{name:'新建例会',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'新建例会',exact:true});
  await dialog.getByLabel('会议日期',{exact:false}).fill('2026-10-24');
  await dialog.locator('[name=meetingTime]').fill('23:00');
  await dialog.getByLabel('开始日',{exact:true}).fill('2026-10-17');
  await dialog.getByLabel('结束日',{exact:true}).fill('2026-10-22');
  await page.evaluate(()=>document.fonts.ready);await page.waitForTimeout(450);
  await page.screenshot({path:folder+'/create-ready-1440.png'});
  const endpoint=fixture.baseURL+'/api/meeting-reviews';
  await page.route(endpoint,(route:any)=>route.fulfill({status:403,contentType:'text/plain',body:'Cross-site POST form submissions are forbidden'}));
  await dialog.getByRole('button',{name:'创建空白模板',exact:true}).click();
  await dialog.locator('output').filter({hasText:'创建失败（403）'}).waitFor();
  assert.equal(await dialog.locator('[name=meetingDate]').inputValue(),'2026-10-24');
  assert.equal(await dialog.locator('[name=periodStart]').inputValue(),'2026-10-17');
  assert.equal(await dialog.locator('[name=periodEnd]').inputValue(),'2026-10-22');
  assert.equal(await dialog.getByRole('button',{name:'创建空白模板',exact:true}).isEnabled(),true);
  assert.equal(await page.locator('[data-session-message]').textContent(),'提交被拒绝，请刷新页面后重试。');
  await page.screenshot({path:folder+'/create-rejected-1440.png'});
  await page.unroute(endpoint);
  await page.route(endpoint,(route:any)=>route.fulfill({status:422,json:{message:'例会只汇总今天以前的数据。'}}));
  await dialog.getByRole('button',{name:'创建空白模板',exact:true}).click();
  await dialog.locator('output').filter({hasText:'例会只汇总今天以前的数据。'}).waitFor();
  await page.unroute(endpoint);
  await page.route(endpoint,(route:any)=>route.abort('internetdisconnected'));
  await dialog.getByRole('button',{name:'创建空白模板',exact:true}).click();
  await dialog.locator('output').filter({hasText:'连接失败，输入已保留'}).waitFor();
  assert.equal((await fixture.db.select().from(s.operationsReviewMeeting)).length,0);
  await page.unroute(endpoint);
  checks.push('非JSON 403显示真实状态而非连接失败；422沿用业务提示；断网保留输入；失败不创建会议');
  let writes=0;
  await page.route(endpoint,async(route:any)=>{writes++;await new Promise(resolve=>setTimeout(resolve,800));await route.continue();});
  await dialog.getByRole('button',{name:'创建空白模板',exact:true}).click();
  await dialog.getByRole('button',{name:'正在创建…',exact:true}).waitFor();
  assert.equal(await dialog.getByRole('button',{name:'正在创建…',exact:true}).isEnabled(),false);
  await dialog.locator('[name=name]').press('Enter');
  await page.waitForURL('**/business/meeting-review?meeting=*',{timeout:15000});
  await page.locator('[data-report-v4]').waitFor();await page.evaluate(()=>document.fonts.ready);await page.waitForTimeout(450);
  await page.screenshot({path:folder+'/created-meeting-1440.png'});
  const meetings=await fixture.db.select().from(s.operationsReviewMeeting);
  assert.equal(meetings.length,1);assert.equal(writes,1);
  assert.equal(meetings[0].meetingAt.toISOString(),'2026-10-24T15:00:00.000Z');
  assert.equal(meetings[0].name,'2026.10.17—10.22 周度业务复盘');
  checks.push('真实拆分表单成功创建并进入会议；连续提交仅写一次；23:00正确存为上海时间；空标题自动生成');
  await page.getByRole('link',{name:'返回例会总览',exact:true}).click();
  await page.locator('.meeting-ledger tbody td').filter({hasText:'2026-10-24 23:00'}).waitFor();
  await page.screenshot({path:folder+'/overview-created-1440.png'});
  assert.deepEqual(errors,[]);
  await writeFile(folder+'/checks.json',JSON.stringify({checks,errors,requests,scope:'真实组件；隔离PGlite、虚构会议；桌面1440px'},null,2));
  console.log(JSON.stringify({checks,folder}));
}catch(error){console.error(fixture.logs());throw error;}finally{await browser?.close();await fixture.stop();}
